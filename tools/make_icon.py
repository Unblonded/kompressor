"""Renders the Kompressor app icon: two arrows squeezing a violet bar on a dark rounded tile.

Usage:  python tools/make_icon.py [out_dir]
Writes  icon_{1024,512,256,128,64,32,16}.png, kompressor.ico (every Windows size) and kompressor.icns
into out_dir (default: packaging/icons). The default run also refreshes src/gui/app_icon_data.inc,
the copy compiled into the app. Only needs Pillow; drawn at 2x and downsampled for anti-aliasing.
"""
import lzma
import os
import sys

from PIL import Image, ImageDraw, ImageFilter

SS = 2                    # supersampling factor
N = 1024 * SS             # working canvas
C = N // 2
INK = (244, 244, 250)
VIOLET_TOP = (160, 132, 255)
VIOLET_BOTTOM = (112, 78, 240)


def s(v):
    return int(round(v * SS))


def vgrad(top, bottom):
    """Full-canvas vertical RGBA gradient."""
    mask = Image.linear_gradient("L").resize((N, N))
    return Image.composite(Image.new("RGBA", (N, N), bottom), Image.new("RGBA", (N, N), top), mask)


def fill(mask, source):
    out = Image.new("RGBA", (N, N), (0, 0, 0, 0))
    out.paste(source, (0, 0), mask)
    return out


def tile(img):
    inset, rad = s(84), s(200)
    box = (inset, inset, N - inset, N - inset)
    # soft drop shadow
    shadow = Image.new("L", (N, N), 0)
    ImageDraw.Draw(shadow).rounded_rectangle((box[0], box[1] + s(18), box[2], box[3] + s(18)), radius=rad, fill=110)
    img.alpha_composite(fill(shadow.filter(ImageFilter.GaussianBlur(s(26))), Image.new("RGBA", (N, N), (0, 0, 0, 255))))
    # graphite body with a faint rim light
    body = Image.new("L", (N, N), 0)
    ImageDraw.Draw(body).rounded_rectangle(box, radius=rad, fill=255)
    img.alpha_composite(fill(body, vgrad((46, 47, 58, 255), (20, 21, 27, 255))))
    rim = Image.new("RGBA", (N, N), (0, 0, 0, 0))
    ImageDraw.Draw(rim).rounded_rectangle(box, radius=rad, outline=(255, 255, 255, 34), width=s(4))
    img.alpha_composite(rim)


def arrow_down(d, tip_y):
    """Arrow pointing down with its tip at tip_y, centred horizontally."""
    head_w, head_h, stem_w, stem_h = s(300), s(150), s(110), s(130)
    d.rectangle((C - stem_w // 2, tip_y - head_h - stem_h, C + stem_w // 2, tip_y - head_h + s(6)), fill=255)
    d.polygon([(C - head_w // 2, tip_y - head_h), (C + head_w // 2, tip_y - head_h), (C, tip_y)], fill=255)


def render():
    img = Image.new("RGBA", (N, N), (0, 0, 0, 0))
    tile(img)

    arrows = Image.new("L", (N, N), 0)
    arrow_down(ImageDraw.Draw(arrows), C - s(70))
    arrows.paste(255, (0, 0), arrows.transpose(Image.FLIP_TOP_BOTTOM))  # mirrored arrow from below
    bar = Image.new("L", (N, N), 0)
    ImageDraw.Draw(bar).rounded_rectangle((C - s(250), C - s(38), C + s(250), C + s(38)), radius=s(38), fill=255)

    for mask, source in ((arrows, Image.new("RGBA", (N, N), INK + (255,))),
                         (bar, vgrad(VIOLET_TOP + (255,), VIOLET_BOTTOM + (255,)))):
        shade = mask.point(lambda v: int(v * 0.35)).filter(ImageFilter.GaussianBlur(s(14)))
        img.alpha_composite(fill(shade, Image.new("RGBA", (N, N), (0, 0, 0, 255))), (0, s(10)))
        img.alpha_composite(fill(mask, source))

    return img.resize((1024, 1024), Image.LANCZOS)


def small(icon, size):
    """Downscale with a touch of sharpening so the glyph stays crisp at 16-32 px."""
    im = icon.resize((size, size), Image.LANCZOS)
    if size <= 48:
        im = im.filter(ImageFilter.UnsharpMask(radius=0.6, percent=60, threshold=0))
    return im


EMBED_SIZES = (32, 64, 128, 256)


def write_embed(icon, path):
    """Embed straight-alpha RGBA at a few sizes, xz-compressed (liblzma is already linked)."""
    raw = b"".join(small(icon, sz).convert("RGBA").tobytes() for sz in EMBED_SIZES)
    blob = lzma.compress(raw, format=lzma.FORMAT_XZ, check=lzma.CHECK_CRC32, preset=9 | lzma.PRESET_EXTREME)
    lines = ["// Generated by tools/make_icon.py - do not edit.",
             f"// RGBA images of {', '.join(str(s) for s in EMBED_SIZES)} px, concatenated and xz-compressed.",
             f"static const int kIconSizes[] = {{{', '.join(str(s) for s in EMBED_SIZES)}}};",
             f"static const unsigned long kIconRawSize = {len(raw)}ul;",
             f"static const unsigned char kIconXz[{len(blob)}] = {{"]
    for i in range(0, len(blob), 24):
        lines.append("  " + ",".join(str(b) for b in blob[i:i + 24]) + ",")
    lines.append("};")
    with open(path, "w", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote", os.path.abspath(path), f"({len(blob)} bytes compressed)")


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(here, "..", "packaging", "icons")
    os.makedirs(out, exist_ok=True)
    icon = render()
    icon.save(os.path.join(out, "icon_1024.png"))
    for sz in (512, 256, 128, 64, 32, 16):
        small(icon, sz).save(os.path.join(out, f"icon_{sz}.png"))
    sizes = [16, 20, 24, 32, 40, 48, 64, 96, 128, 256]
    frames = [small(icon, sz) for sz in sizes]
    frames[-1].save(os.path.join(out, "kompressor.ico"), format="ICO", sizes=[(sz, sz) for sz in sizes],
                    append_images=frames[:-1])
    icon.save(os.path.join(out, "kompressor.icns"))
    print("wrote", os.path.abspath(out))
    if len(sys.argv) <= 1:
        write_embed(icon, os.path.join(here, "..", "src", "gui", "app_icon_data.inc"))


if __name__ == "__main__":
    main()
